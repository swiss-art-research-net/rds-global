import argparse
from pathlib import Path

from lib.utils import RDS_ONTOLOGY_NAMESPACE, load_config


GENERATED_HEADER = """# This file is automatically generated.\n# Do not edit it manually.\n#\n# It combines the stable RDS type ontology with mappings declared in the\n# active datasets configuration.\n\n"""


def expand_type_reference(type_reference: str, prefixes: dict[str, str]) -> str:
    """Return a Turtle IRI for an absolute IRI or a configured CURIE."""
    if type_reference.startswith(("http://", "https://")):
        return f"<{type_reference}>"

    prefix, separator, local_name = type_reference.partition(":")
    if not separator or not local_name:
        raise ValueError(
            f"Type reference '{type_reference}' must be an absolute IRI or a CURIE"
        )
    if prefix not in prefixes:
        raise ValueError(
            f"Type reference '{type_reference}' uses undefined prefix '{prefix}'"
        )

    return f"<{prefixes[prefix]}{local_name}>"


def generate_type_mapping_rdf(*, config: str, ontology_file: str, output_file: str) -> None:
    """Generate external RDF class to RDS type subclass mappings.

    Dataset configuration has the form ``types: {RdsType: [external:Class]}``.
    Each configured external class is therefore emitted as an
    ``rdfs:subClassOf`` the corresponding RDS type.
    """
    config_data = load_config(config) or {}
    rds_types = config_data.get("types", {})
    datasets = config_data.get("datasets", {})

    if not rds_types:
        raise ValueError("The datasets configuration does not define any RDS types")

    ontology_path = Path(ontology_file)
    if not ontology_path.exists():
        raise FileNotFoundError(f"RDS type ontology not found: {ontology_path}")

    mappings: set[tuple[str, str]] = set()
    for dataset_id, dataset in datasets.items():
        prefixes = {"rds": RDS_ONTOLOGY_NAMESPACE, **(dataset.get("prefixes") or {})}
        for rds_type, external_types in (dataset.get("types") or {}).items():
            if rds_type not in rds_types:
                raise ValueError(
                    f"Dataset '{dataset_id}' maps to unknown RDS type '{rds_type}'"
                )
            if not isinstance(external_types, list):
                raise ValueError(
                    f"Dataset '{dataset_id}' type '{rds_type}' must be a list of RDF classes"
                )

            rds_type_iri = f"<{RDS_ONTOLOGY_NAMESPACE}{rds_type}>"
            for external_type in external_types:
                if not isinstance(external_type, str):
                    raise ValueError(
                        f"Dataset '{dataset_id}' type '{rds_type}' contains a non-string RDF class"
                    )
                external_type_iri = expand_type_reference(external_type, prefixes)
                if external_type_iri != rds_type_iri:
                    mappings.add((external_type_iri, rds_type_iri))

    rendered_mappings = "".join(
        f"{external_type} rdfs:subClassOf {rds_type} .\n"
        for external_type, rds_type in sorted(mappings)
    )

    ontology = ontology_path.read_text(encoding="utf-8").rstrip()
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        f"{GENERATED_HEADER}{ontology}\n\n# Dataset type mappings\n\n{rendered_mappings}",
        encoding="utf-8",
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Generate RDF subclass mappings from the datasets configuration"
    )
    parser.add_argument("--config", required=True, help="Path to YAML datasets configuration")
    parser.add_argument(
        "--ontology-file", required=True, help="Path to the stable RDS type ontology Turtle file"
    )
    parser.add_argument("--output-file", required=True, help="Path to generated Turtle file")
    args = parser.parse_args()

    generate_type_mapping_rdf(
        config=args.config,
        ontology_file=args.ontology_file,
        output_file=args.output_file,
    )
